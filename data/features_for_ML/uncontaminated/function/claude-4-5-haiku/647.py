def larx(n: int) -> CayleyGraphDef:
    """
    Cayley graph for S_n (n >= 2), generated by transposition-based permutations.
    Creates two generators: one with 0,1 transposition and one with cyclic shift.
    """
    if n < 2:
        raise ValueError("n must be >= 2")
    
    # Generate all permutations of [0, 1, ..., n-1]
    from itertools import permutations
    
    all_perms = list(permutations(range(n)))
    perm_to_idx = {perm: idx for idx, perm in enumerate(all_perms)}
    
    # Generator 1: Swap positions 0 and 1
    def gen1(perm):
        perm_list = list(perm)
        perm_list[0], perm_list[1] = perm_list[1], perm_list[0]
        return tuple(perm_list)
    
    # Generator 2: Cyclic shift right (last element moves to front)
    def gen2(perm):
        perm_list = list(perm)
        return tuple([perm_list[-1]] + perm_list[:-1])
    
    # Build adjacency lists
    adjacency = [[] for _ in range(len(all_perms))]
    
    for idx, perm in enumerate(all_perms):
        # Apply generator 1
        next_perm_1 = gen1(perm)
        next_idx_1 = perm_to_idx[next_perm_1]
        adjacency[idx].append(next_idx_1)
        
        # Apply generator 2
        next_perm_2 = gen2(perm)
        next_idx_2 = perm_to_idx[next_perm_2]
        adjacency[idx].append(next_idx_2)
    
    # Create node labels
    node_labels = [str(perm) for perm in all_perms]
    
    # Create edge labels
    edge_labels = [["swap(0,1)", "rotate"] for _ in range(len(all_perms))]
    
    return CayleyGraphDef(
        nodes=len(all_perms),
        adjacency=adjacency,
        node_labels=node_labels,
        edge_labels=edge_labels
    )