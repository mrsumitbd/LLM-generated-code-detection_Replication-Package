def parse_log_calypso(log: str, test_spec: "TestSpec") -> dict[str, str]:
    """
    Parser for test logs generated by Calypso test suite
    """
    result = {}
    lines = log.split('\n')
    
    current_section = None
    current_content = []
    
    for line in lines:
        line_stripped = line.strip()
        
        # Check if this is a section header
        if line_stripped.startswith('[') and line_stripped.endswith(']'):
            # Save previous section if exists
            if current_section is not None:
                result[current_section] = '\n'.join(current_content).strip()
            
            # Start new section
            current_section = line_stripped[1:-1]
            current_content = []
        elif current_section is not None:
            current_content.append(line)
    
    # Save last section
    if current_section is not None:
        result[current_section] = '\n'.join(current_content).strip()
    
    # Extract key metrics and status information
    parsed_result = {}
    
    for key, value in result.items():
        parsed_result[key] = value
    
    # Look for common test result indicators
    log_lower = log.lower()
    
    if 'passed' in log_lower:
        parsed_result['status'] = 'PASSED'
    elif 'failed' in log_lower:
        parsed_result['status'] = 'FAILED'
    elif 'error' in log_lower:
        parsed_result['status'] = 'ERROR'
    else:
        parsed_result['status'] = 'UNKNOWN'
    
    # Extract test name if available
    for line in lines:
        if 'test' in line.lower() and ':' in line:
            parts = line.split(':')
            if len(parts) >= 2:
                parsed_result['test_name'] = parts[1].strip()
                break
    
    # Extract duration if available
    for line in lines:
        if 'duration' in line.lower() or 'time' in line.lower():
            parsed_result['duration'] = line.strip()
            break
    
    return parsed_result