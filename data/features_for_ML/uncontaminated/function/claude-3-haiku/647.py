from typing import Tuple
from dataclasses import dataclass

@dataclass
class CayleyGraphDef:
    generators: Tuple[Tuple[int, ...], Tuple[int, ...]]

def larx(n: int) -> CayleyGraphDef:
    """
    Cayley graph for S_n (n >= 2), generated by transposition-based permutations.
    Creates two generators: one with 0,1 transposition and one with cyclic shift.
    """
    if n < 2:
        raise ValueError("n must be at least 2")

    transposition = tuple(range(n))
    transposition[0], transposition[1] = transposition[1], transposition[0]

    cyclic_shift = tuple(range(1, n)) + (0,)

    return CayleyGraphDef(generators=(transposition, cyclic_shift))