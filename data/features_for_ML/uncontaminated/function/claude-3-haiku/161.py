def parse_log_calypso(log: str, test_spec: "TestSpec") -> dict[str, str]:
    """
    Parser for test logs generated by Calypso test suite
    """
    result = {}
    lines = log.splitlines()
    for line in lines:
        if ":" in line:
            key, value = line.split(":", 1)
            key = key.strip()
            value = value.strip()
            result[key] = value
    return result